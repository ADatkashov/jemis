def meta(ru):
    import re
    ph = re.findall(r"\{(\w+)\}", ru)
    if not ph: return None
    return {"placeholders": {p: {"type": "String"} for p in ph}}

out_dir = os.path.join(os.path.dirname(__file__), "..", "lib", "l10n")
for i, lang in enumerate(["ru", "kk", "en"]):
    d = {"@@locale": lang}
    for k, v in T.items():
        d[k] = v[i]
        if lang == "ru":
            m = meta(v[0])
            if m: d["@" + k] = m
    with open(os.path.join(out_dir, f"app_{lang}.arb"), "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
        f.write("\n")
print(len(T), "keys")
