def meta(ru):
    ph = re.findall(r"\{(\w+)\}", ru)
    if not ph: return None
    return {"placeholders": {p: {"type": "String"} for p in ph}}

out_dir = os.path.join(os.path.dirname(__file__), "..", "lib", "l10n")
os.makedirs(out_dir, exist_ok=True)
for i, lang in enumerate(["ru", "kk", "en"]):
    d = {"@@locale": lang}
    for k, v in T.items():
        d[k] = v[i]
        if lang == "ru":
            m = meta(v[0])
